-- Issues: #255, #285, #331

CREATE TABLE IF NOT EXISTS public.conteudo_pendente (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pergunta_usuario text NOT NULL,
    resposta_vox text NOT NULL,
    tags text[] DEFAULT '{}'::text[],
    fonte_original text,
    data_referencia timestamp with time zone DEFAULT now(),
    status text NOT NULL DEFAULT 'PENDING_REVIEW' CHECK (status IN ('PENDING_REVIEW', 'APPROVED', 'REJECTED')),
    criado_em timestamp with time zone DEFAULT now(),
    revisado_por text,
    revisado_em timestamp with time zone,
    notas_revisao text,
    kb_id text
);

ALTER TABLE public.conteudo_pendente OWNER TO postgres;

-- Índices para buscas rápidas por status e data de criação
CREATE INDEX IF NOT EXISTS idx_conteudo_pendente_status ON public.conteudo_pendente (status);
CREATE INDEX IF NOT EXISTS idx_conteudo_pendente_criado_em ON public.conteudo_pendente (criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_conteudo_pendente_kb_id ON public.conteudo_pendente (kb_id);

-- Habilitar RLS (Row Level Security)
ALTER TABLE public.conteudo_pendente ENABLE ROW LEVEL SECURITY;

-- Políticas de segurança
CREATE POLICY "Permitir leitura de conteudo_pendente para anon, authenticated e service_role"
    ON public.conteudo_pendente
    AS PERMISSIVE
    FOR SELECT
    TO anon, authenticated, service_role
    USING (true);

CREATE POLICY "Permitir insercao de conteudo_pendente para anon, authenticated e service_role"
    ON public.conteudo_pendente
    AS PERMISSIVE
    FOR INSERT
    TO anon, authenticated, service_role
    WITH CHECK (true);

CREATE POLICY "Permitir atualizacao de conteudo_pendente para service_role e authenticated"
    ON public.conteudo_pendente
    AS PERMISSIVE
    FOR UPDATE
    TO service_role, authenticated
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Permitir delecao de conteudo_pendente para service_role"
    ON public.conteudo_pendente
    AS PERMISSIVE
    FOR DELETE
    TO service_role
    USING (true);

-- Permissões de tabelas e sequences
GRANT ALL ON TABLE public.conteudo_pendente TO anon;
GRANT ALL ON TABLE public.conteudo_pendente TO authenticated;
GRANT ALL ON TABLE public.conteudo_pendente TO service_role;
GRANT ALL ON SEQUENCE public.conteudo_pendente_id_seq TO anon, authenticated, service_role;
